"""Regenerate docs/how_chain/how_detail.yaml from the code itself.

The two how-chain levels below each file (file -> its top-level classes
and functions, class -> its methods) link two real Python entities, so
neither end can own a ``how`` component; they're ``how_link`` rows held
by one index entity instead (see that file's own description). Questions
already worded by hand in the existing file are kept across a
regeneration; anything still generic is (re)filled from default_question.

Usage: uv run python scripts/generate_how_detail.py
"""

from __future__ import annotations

import ast
import re
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
CODE_DIRS = ["story_simulator", "tests", "scripts"]
OUT = REPO / "docs" / "how_chain" / "how_detail.yaml"

HEADER = {
    "file_info": [
        {
            "description": (
                "Generated by scripts/generate_how_detail.py -- edit question wording "
                "here freely (it's kept on regeneration), but regenerate rather than "
                "hand-adding edges. The how-chain edges below the file level: each file "
                "to its own top-level classes/functions, and each class to its own "
                "methods. Both ends are real Python entities, so these are how_link rows "
                "with an explicit source, all held by how_chain_detail."
            )
        },
        "file_info",
    ],
    "how_link": [
        {
            "description": (
                "A how-chain edge naming both ends explicitly (`source` and `value`), "
                "for links between two Python-sourced entities, neither of which can "
                "own a new component from YAML."
            )
        },
        {"parent": "directed_relation"},
        {
            "field": {
                "source": {"description": "The entity that asks how it is achieved.", "type": "entity_ref"},
                "value": {"description": "The entity that is how the source gets achieved.", "type": "entity_ref"},
                "question": {"description": "The \"how\" question this link answers.", "type": "str"},
                "note": {"description": "Optional side note about this link.", "type": "str", "nullable": True},
            }
        },
    ],
}


# Default questions don't count as hand-edited, so a better default replaces them.
GENERIC = re.compile(r"How is `\w+` implemented\?|How is it verified that [^?]*\?")


def default_question(name: str) -> str:
    """Generic question for an edge nobody has worded by hand yet."""
    if name.startswith("test_"):
        return f"How is it verified that {name[5:].replace('_', ' ')}?"
    return f"How is `{name}` implemented?"


def module_key(path: Path) -> str:
    """Dotted entity key emc2p's load_python gives `path` (``__init__`` kept)."""
    return ".".join(path.relative_to(REPO).with_suffix("").parts)


def edges() -> list[tuple[str, str, str]]:
    """(source_key, value_key, name) for every file->def and class->method edge."""
    out = []
    for d in CODE_DIRS:
        for path in sorted((REPO / d).rglob("*.py")):
            mod = module_key(path)
            tree = ast.parse(path.read_text())
            for node in tree.body:
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and ast.get_docstring(node):
                    out.append((mod, f"{mod}.{node.name}", node.name))
                    if isinstance(node, ast.ClassDef):
                        for m in node.body:
                            if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)) and ast.get_docstring(m):
                                out.append((f"{mod}.{node.name}", f"{mod}.{node.name}.{m.name}", m.name))
    return out


def short_refs(keys: set[str]) -> dict[str, str]:
    """Shortest dotted suffix (2+ parts) of each key that no other key shares."""
    refs = {}
    for k in keys:
        parts = k.split(".")
        for n in range(2, len(parts) + 1):
            suffix = ".".join(parts[-n:])
            if not any(o != k and (o == suffix or o.endswith("." + suffix)) for o in keys):
                refs[k] = suffix
                break
        else:
            refs[k] = k
    return refs


def main() -> None:
    """Write how_detail.yaml, keeping existing questions, then verify every link resolves."""
    from emc2p.registrar import Registrar

    existing = {}
    if OUT.exists():
        for row in (yaml.safe_load(OUT.read_text()).get("how_chain_detail") or []):
            for link in row.get("how_link", []) if isinstance(row, dict) else []:
                if not GENERIC.fullmatch(link["question"]):
                    existing[(link["source"], link["value"])] = link["question"]

    es = edges()
    registrar = Registrar.from_manifest([str(REPO / d) for d in CODE_DIRS])
    ids = registrar.registry.get("entity_id").to_pandas()
    all_keys = set(ids["path"].astype(str).str.split(":", n=1).str[1])
    refs = short_refs(all_keys)

    links = []
    for src, val, name in sorted(es, key=lambda e: (refs[e[0]], refs[e[1]])):
        s, v = refs[src], refs[val]
        links.append({"source": s, "value": v, "question": existing.get((s, v)) or default_question(name)})
    doc = dict(HEADER)
    doc["how_chain_detail"] = [
        {"description": "Every how_link edge below the file level (see how_link)."},
        {"how_link": links},
    ]
    OUT.write_text(yaml.safe_dump(doc, sort_keys=False, width=100, allow_unicode=True))

    # Verify: every how/how_link endpoint resolves to the intended entity.
    full = Registrar.from_manifest([str(OUT.parent)] + [str(REPO / d) for d in CODE_DIRS]).registry
    ids = full.get("entity_id").to_pandas()
    key_of = dict(zip(ids["value"], ids["path"].astype(str).str.split(":", n=1).str[1]))
    bad = []
    rows = full.get("how_link").to_pandas().to_dict("records")
    for (src, val, _), row in zip(sorted(es, key=lambda e: (refs[e[0]], refs[e[1]])), sorted(rows, key=lambda r: (r["source"], r["value"]))):
        if key_of.get(row["source_eid"]) != src or key_of.get(row["value_eid"]) != val:
            bad.append((row["source"], row["value"]))
    for row in full.get("how").to_pandas().to_dict("records"):
        if row["value_eid"] not in key_of:
            bad.append((row["entity_id"], row["value"]))
    print(f"wrote {len(links)} how_link edges to {OUT.relative_to(REPO)}; unresolved/mismatched: {bad or 'none'}")
    if bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
