def _dotted(node) -> str | None:
    """`a.b.c` for a Name/Attribute chain (through a call's func, e.g. `a.b().c`), else None."""
    parts = []
    while True:
        if isinstance(node, ast.Attribute):
            parts.append(node.attr)
            node = node.value
        elif isinstance(node, ast.Call):
            node = node.func
        elif isinstance(node, ast.Name):
            return ".".join([node.id] + parts[::-1])
        else:
            return None


def _bind(names: dict[str, str], dotted: str | None) -> str | None:
    """Rewrite `dotted`'s head through `names` (local name -> story_simulator target)."""
    if not dotted:
        return None
    head, _, rest = dotted.partition(".")
    if head == "self" and "self" in names:
        head, _, rest = rest.partition(".") if rest else ("", "", "")
        return f"{names['self']}.{head}" + (f".{rest}" if rest else "") if head else None
    if head not in names:
        return None
    return names[head] + (f".{rest}" if rest else "")


def _module_names(tree: ast.Module) -> dict[str, str]:
    """Imports of story_simulator (anywhere in the file) plus module-level aliases of them."""
    names = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and (node.module or "").startswith("story_simulator"):
            for a in node.names:
                names[a.asname or a.name] = f"{node.module}.{a.name}"
        elif isinstance(node, ast.Import):
            for a in node.names:
                if a.name.startswith("story_simulator"):
                    names[a.asname or a.name.split(".")[0]] = a.name if a.asname else a.name.split(".")[0]
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if (b := _bind(names, _dotted(node.value))):
                names[node.targets[0].id] = b
    return names


def _calls(fn, names: dict[str, str]) -> list[str]:
    """Calls in `fn`, in source order, bound through `names` plus fn's own local assignments."""
    names = dict(names)
    for node in sorted(ast.walk(fn), key=lambda n: getattr(n, "lineno", 0)):
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if (b := _bind(names, _dotted(node.value))):
                names[node.targets[0].id] = b
    # Calls, plus bare references (e.g. pytest.raises(NeedsExternalInput)); inner Attribute
    # nodes of a chain are skipped so `a.b.c` yields one entry, not three.
    inner = {id(n.value) for n in ast.walk(fn) if isinstance(n, ast.Attribute)}
    inner |= {id(n.func) for n in ast.walk(fn) if isinstance(n, ast.Call)}
    raw = [_dotted(n.func) if isinstance(n, ast.Call) else _dotted(n)
           for n in sorted(ast.walk(fn), key=lambda n: (getattr(n, "lineno", 0), getattr(n, "col_offset", 0)))
           if isinstance(n, ast.Call) or (isinstance(n, (ast.Name, ast.Attribute)) and id(n) not in inner)]
    return [c for c in raw if c]


def _snake(name: str) -> str:
    """`TurnReplay` -> `turn_replay`; `_save_pending` -> `save_pending`."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower().strip("_")


def test_links(refs: dict[str, str], hand_written: set[str]) -> list[dict]:
    """Every test (test_* function or method under tests/) -> the node(s) it tests.

    Tests in `hand_written` (keys of tests whose docstring declares their
    own ``tests`` components) are skipped: their hand-written links win.
    """
    targets = {k for k in refs if k.startswith(("story_simulator.", "scripts."))}

    def resolve(bound: str | None) -> str | None:
        if not bound:
            return None
        parts = bound.split(".")
        if parts[:3] == ["story_simulator", "core", "registrar_sessions"] and len(parts) > 3 and parts[3] in REGISTRY_TOOLS:
            return f"tool_{parts[3]}"
        for i in range(len(parts), 1, -1):
            if ".".join(parts[:i]) in targets:
                return refs[".".join(parts[:i])]
        return None

    conftest = ast.parse((REPO / "tests" / "conftest.py").read_text())
    conftest_fns = {n.name: n for n in conftest.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))}
    conftest_names = _module_names(conftest)
    links = []
    for path in sorted((REPO / "tests").rglob("*.py")):
        module = module_key(path)
        tree = ast.parse(path.read_text())
        names = _module_names(tree)
        local_fns = {n.name: n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))}
        scopes = [(None, n) for n in tree.body] + [
            (c, m) for c in tree.body if isinstance(c, ast.ClassDef) for m in c.body]
        for cls, fn in scopes:
            if not isinstance(fn, (ast.FunctionDef, ast.AsyncFunctionDef)) or not fn.name.startswith("test_"):
                continue
            key = f"{module}.{cls.name}.{fn.name}" if cls else f"{module}.{fn.name}"
            if key not in refs or key in hand_written:
                continue
            methods = {m.name: m for m in cls.body if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef))} if cls else {}
            found = next((v for suffix, v in TEST_OVERRIDES.items()
                          if f"{module}.".endswith(f".{suffix}.") or f".{suffix}." in f"{module}."), None)
            if found is None:
                calls = _calls(fn, names)
                found = [r for c in calls if (r := resolve(_bind(names, c)))]
                for c in calls:  # one level through local, class, or conftest helpers
                    if resolve(_bind(names, c)):
                        continue
                    head = c.split(".")[0] if not c.startswith("self.") else c.split(".")[1]
                    helper, hnames = (
                        (methods.get(head), names) if c.startswith("self.")
                        else (local_fns.get(head), names) if head in local_fns
                        else (conftest_fns.get(head), conftest_names))
                    if helper is not None and helper is not fn:
                        found += [r for c2 in _calls(helper, hnames) if (r := resolve(_bind(hnames, c2)))]
                # Prefer what the test is named after over setup calls (start_world, ...).
                named = [v for v in found if _snake(re.split(r"[.]|__", v)[-1].removeprefix("tool_")) in fn.name]
                found = named or found
            for v in dict.fromkeys(found):
                links.append({"source": refs[key], "value": v})
    return links


def main() -> None:
    """Write how_detail.yaml, keeping existing questions, then verify every link resolves."""
    from emc2p.registrar import Registrar

    existing = {}
    if OUT.exists():
        for row in (yaml.safe_load(OUT.read_text()).get("how_chain_detail") or []):
            for link in row.get("how_link", []) if isinstance(row, dict) else []:
                if link.get("question") and not GENERIC.fullmatch(link["question"]):
                    existing[(link["source"], link["value"])] = link["question"]

    edges, variables = objects()
    registrar = Registrar.from_manifest([str(REPO / d) for d in CODE_DIRS])
    ids = registrar.registry.get("entity_id").to_pandas()
    refs = short_refs(set(ids["path"].astype(str).str.split(":", n=1).str[1]) | set(variables))
    # Stand-in entity names: dots would read as Python refs, so join with "__".
    for k in variables:
        refs[k] = refs[k].replace(".", "__")

    undocumented = sorted({e[0] for e in edges} - set(refs))
    if undocumented:
        raise SystemExit(f"these contain objects but have no docstring, so emc2p can't load them: {undocumented}")

    links, expected = [], {}
    for src, val, _name, is_var in sorted(edges, key=lambda e: (refs[e[0]], refs[e[1]])):
        s, v = refs[src], refs[val]
        link = {"source": s, "value": v}
        if existing.get((s, v)):
            link["question"] = existing[(s, v)]
        links.append(link)
        expected[(s, v)] = (src, refs[val] if is_var else val)
    doc = dict(HEADER)
    doc["how_chain_detail"] = [
        {"description": "Every how_link edge below the file level (see how_link)."},
        {"how_link": links},
    ]
    for k in sorted(variables, key=lambda k: refs[k]):
        doc[refs[k]] = [{"description": variables[k]["description"]},
                        {"source_file": variables[k]["source_file"]}]
    OUT.write_text(yaml.safe_dump(doc, sort_keys=False, width=100, allow_unicode=True))

    hand_ids = registrar.registry.get("entity_id").to_pandas()
    hand_key = dict(zip(hand_ids["value"], hand_ids["path"].astype(str).str.split(":", n=1).str[1]))
    hand_written = (
        {hand_key[e] for e in registrar.registry.get("tests").to_pandas()["entity_id"]}
        if "tests" in registrar.registry.component_types else set())
    tlinks = test_links(refs, hand_written)
    tdoc = dict(TEST_HEADER)
    tdoc["test_index"] = [{"description": "Every test link (see test)."}, {"test": tlinks}]
    TEST_OUT.write_text(yaml.safe_dump(tdoc, sort_keys=False, width=100, allow_unicode=True))

    # Verify: every how/how_link endpoint resolves to the intended entity.
    full = Registrar.from_manifest([str(OUT.parent)] + [str(REPO / d) for d in CODE_DIRS]).registry
    ids = full.get("entity_id").to_pandas()
    key_of = dict(zip(ids["value"], ids["path"].astype(str).str.split(":", n=1).str[1]))
    bad = []
    for row in full.get("how_link").to_pandas().to_dict("records"):
        want = expected.get((row["source"], row["value"]))
        if want is None or (key_of.get(row["source_eid"]), key_of.get(row["value_eid"])) != want:
            bad.append((row["source"], row["value"]))
    for row in full.get("how").to_pandas().to_dict("records"):
        if row["value_eid"] not in key_of:
            bad.append((row["entity_id"], row["value"]))
    for row in full.get("test").to_pandas().to_dict("records"):
        if row["source_eid"] not in key_of or row["value_eid"] not in key_of:
            bad.append(("test", row["source"], row["value"]))
    hand_rows = full.get("tests").to_pandas().to_dict("records") if "tests" in full.component_types else []
    for row in hand_rows:  # hand-written links must name a real node
        if row["value_eid"] not in key_of:
            bad.append(("tests", key_of.get(row["entity_id"]), row["value"]))
    tested = {r["source"] for r in tlinks} | {refs[k] for k in hand_written}
    all_tests = {refs[k] for k in refs if k.startswith("tests.") and k.rsplit(".", 1)[-1].startswith("test_")
                 and not (REPO / (k.replace(".", "/") + ".py")).exists()}
    print(f"wrote {len(links)} how_link edges ({len(variables)} variable stand-ins) "
          f"to {OUT.relative_to(REPO)}; test links for {len(tested)}/{len(all_tests)} tests: "
          f"{len(tlinks)} inferred (in {TEST_OUT.relative_to(REPO)}), {len(hand_rows)} hand-written "
          f"(on {len(hand_written)} tests); unresolved/mismatched: {bad or 'none'}")
    if all_tests - tested:
        print("untested-link tests:", sorted(all_tests - tested))
    if bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
