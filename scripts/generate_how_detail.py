"""Regenerate docs/how_chain/how_detail.yaml from the code itself.

Every how-chain level below each file: a file, class, or function to
each class/function defined directly in it, and a file or class to each
of its variables. Both ends live in source, so neither can own a ``how``
component; they're ``how_link`` rows held by one index entity instead.
Variables can't carry docstrings, so each gets a generated stand-in
entity (description taken from the comment directly above it). Questions
worded by hand in the existing file are kept across a regeneration; new
edges get none (the value's own name already says what it is).

Usage: uv run python scripts/generate_how_detail.py
"""

from __future__ import annotations

import ast
import re
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
CODE_DIRS = ["story_simulator", "tests", "scripts"]
OUT = REPO / "docs" / "how_chain" / "how_detail.yaml"

HEADER = {
    "file_info": [
        {
            "description": (
                "Generated by scripts/generate_how_detail.py -- edit question wording "
                "here freely (it's kept on regeneration), but regenerate rather than "
                "hand-adding edges (or questions: add one to any link). Every how-chain edge below the file level: each "
                "file, class, or function to the classes/functions defined directly in "
                "it, and each file or class to its variables. Both ends live in source, "
                "so these are how_link rows with an explicit source, all held by "
                "how_chain_detail. Variables can't carry docstrings, so each gets a "
                "stand-in entity below (named with __ for dots), described by the "
                "comment directly above it in source, or by its assignment if none."
            )
        },
        "file_info",
    ],
    "how_link": [
        {
            "description": (
                "A how-chain edge naming both ends explicitly (`source` and `value`), "
                "for links between two Python-sourced entities, neither of which can "
                "own a new component from YAML."
            )
        },
        {"parent": "directed_relation"},
        {
            "field": {
                "source": {"description": "The entity that asks how it is achieved.", "type": "entity_ref"},
                "value": {"description": "The entity that is how the source gets achieved.", "type": "entity_ref"},
                "question": {"description": "The \"how\" question this link answers, if worded "
                             "by hand; omitted when the value's own name says it.",
                             "type": "str", "nullable": True},
                "note": {"description": "Optional side note about this link.", "type": "str", "nullable": True},
            }
        },
    ],
}


# Old auto-generated wording, dropped on regeneration.
GENERIC = re.compile(r"How is `\w+` implemented\?|How is it verified that [^?]*\?|What does `\w+` hold\?")


def module_key(path: Path) -> str:
    """Dotted entity key emc2p's load_python gives `path` (``__init__`` kept)."""
    return ".".join(path.relative_to(REPO).with_suffix("").parts)


def _comment_above(lines: list[str], lineno: int) -> str:
    """The contiguous ``#`` comment block directly above line `lineno`, joined."""
    out = []
    i = lineno - 2
    while i >= 0 and lines[i].strip().startswith("#"):
        out.insert(0, lines[i].strip().lstrip("#").strip())
        i -= 1
    return " ".join(x for x in out if x)


def objects() -> tuple[list[tuple[str, str, str, bool]], dict[str, dict]]:
    """Every object below the file level, as edges plus variable stand-ins.

    Edges are (source_key, value_key, name, is_variable): each module, class,
    or function to the classes/functions defined directly in it, and each
    module or class to its own variables. Variables can't carry a
    docstring, so emc2p can't load them as Python entities; they get a
    stand-in entity instead (returned keyed by value_key). Skipped:
    ``__iacs__`` (loader metadata, not an object), function-local
    variables, and ``if __name__ == "__main__"`` guards.
    """
    edges, variables = [], {}
    for d in CODE_DIRS:
        for path in sorted((REPO / d).rglob("*.py")):
            src = path.read_text()
            lines = src.splitlines()
            rel = path.relative_to(REPO).as_posix()

            def scope(body, key, qual, in_function):
                """Collect edges and variable stand-ins for one body, recursing into defs."""
                for node in body:
                    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                        child = f"{key}.{node.name}"
                        if ast.get_docstring(node):  # emc2p only loads documented objects
                            edges.append((key, child, node.name, False))
                        scope(node.body, child, f"{qual}{node.name}.",
                              in_function or not isinstance(node, ast.ClassDef))
                    elif isinstance(node, (ast.Assign, ast.AnnAssign)) and not in_function:
                        targets = node.targets if isinstance(node, ast.Assign) else [node.target]
                        for t in targets:
                            for name in (n.id for n in ast.walk(t) if isinstance(n, ast.Name)):
                                if name == "__iacs__":
                                    continue
                                stmt = " ".join(ast.get_source_segment(src, node).split())
                                desc = _comment_above(lines, node.lineno) or f"`{stmt[:150]}`"
                                variables[f"{key}.{name}"] = {
                                    "description": desc,
                                    "source_file": f"{rel}::{qual}{name}",
                                }
                                edges.append((key, f"{key}.{name}", name, True))

            scope(ast.parse(src).body, module_key(path), "", False)
    return edges, variables


def short_refs(keys: set[str]) -> dict[str, str]:
    """Shortest dotted suffix (2+ parts) of each key that no other key shares."""
    refs = {}
    for k in keys:
        parts = k.split(".")
        for n in range(2, len(parts) + 1):
            suffix = ".".join(parts[-n:])
            if not any(o != k and (o == suffix or o.endswith("." + suffix)) for o in keys):
                refs[k] = suffix
                break
        else:
            refs[k] = k
    return refs


def main() -> None:
    """Write how_detail.yaml, keeping existing questions, then verify every link resolves."""
    from emc2p.registrar import Registrar

    existing = {}
    if OUT.exists():
        for row in (yaml.safe_load(OUT.read_text()).get("how_chain_detail") or []):
            for link in row.get("how_link", []) if isinstance(row, dict) else []:
                if link.get("question") and not GENERIC.fullmatch(link["question"]):
                    existing[(link["source"], link["value"])] = link["question"]

    edges, variables = objects()
    registrar = Registrar.from_manifest([str(REPO / d) for d in CODE_DIRS])
    ids = registrar.registry.get("entity_id").to_pandas()
    refs = short_refs(set(ids["path"].astype(str).str.split(":", n=1).str[1]) | set(variables))
    # Stand-in entity names: dots would read as Python refs, so join with "__".
    for k in variables:
        refs[k] = refs[k].replace(".", "__")

    undocumented = sorted({e[0] for e in edges} - set(refs))
    if undocumented:
        raise SystemExit(f"these contain objects but have no docstring, so emc2p can't load them: {undocumented}")

    links, expected = [], {}
    for src, val, _name, is_var in sorted(edges, key=lambda e: (refs[e[0]], refs[e[1]])):
        s, v = refs[src], refs[val]
        link = {"source": s, "value": v}
        if existing.get((s, v)):
            link["question"] = existing[(s, v)]
        links.append(link)
        expected[(s, v)] = (src, refs[val] if is_var else val)
    doc = dict(HEADER)
    doc["how_chain_detail"] = [
        {"description": "Every how_link edge below the file level (see how_link)."},
        {"how_link": links},
    ]
    for k in sorted(variables, key=lambda k: refs[k]):
        doc[refs[k]] = [{"description": variables[k]["description"]},
                        {"source_file": variables[k]["source_file"]}]
    OUT.write_text(yaml.safe_dump(doc, sort_keys=False, width=100, allow_unicode=True))

    # Verify: every how/how_link endpoint resolves to the intended entity.
    full = Registrar.from_manifest([str(OUT.parent)] + [str(REPO / d) for d in CODE_DIRS]).registry
    ids = full.get("entity_id").to_pandas()
    key_of = dict(zip(ids["value"], ids["path"].astype(str).str.split(":", n=1).str[1]))
    bad = []
    for row in full.get("how_link").to_pandas().to_dict("records"):
        want = expected.get((row["source"], row["value"]))
        if want is None or (key_of.get(row["source_eid"]), key_of.get(row["value_eid"])) != want:
            bad.append((row["source"], row["value"]))
    for row in full.get("how").to_pandas().to_dict("records"):
        if row["value_eid"] not in key_of:
            bad.append((row["entity_id"], row["value"]))
    print(f"wrote {len(links)} how_link edges ({len(variables)} variable stand-ins) "
          f"to {OUT.relative_to(REPO)}; unresolved/mismatched: {bad or 'none'}")
    if bad:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
